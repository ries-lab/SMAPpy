"""The function index: SMAPpy's public Python functions, for code of one's own.

An agent with Python at hand wrote in numpy what a module of SMAPpy already
does -- which beads to trust, the drift they agree on, a table collapsed to
one row per id -- because `find_plugins` finds plugins and the functions
behind them were found only by reading the code.  Every shipped plugin is a
thin wrapper over module-level functions that take arrays (CLAUDE.md), so
those functions are what code of its own should build on.

Generated by parsing the source with `ast`, never importing it: a module
that imports torch costs nothing here, and a module that fails to import
still has its functions listed.  For each public function and class at a
module's top level: its dotted name, its signature without annotations (the
names and defaults are what a call needs; `read_source` shows the rest) and
the first sentence of its docstring.  Searched as `index.search` searches
the plugins -- word overlap, weighted by where the word was found -- with
two more places to find it: the rest of its docstring, and the paragraphs
of its module's docstring that name it, where this code base explains a
function more often than in the function's own (`beads`: "which ones to
trust" is the module's, `select_beads` names the parameters).
"""
from __future__ import annotations

import ast
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Dict, FrozenSet, Iterable, List, Optional, Tuple

from .index import wanted_words, words

# the folders of smappy that are not for code of one's own: the windows,
# the assistant itself, the tutorials, the help, the command lines and data
_SKIPPED = frozenset({"gui", "assistant", "tutorial", "docs", "cli", "data"})
# how much a word counts by where it was found
_WEIGHTS = (("name", 4.0), ("module", 2.0), ("summary", 2.0),
            ("doc", 1.0), ("context", 1.0))
MAX_SIGNATURE = 300
MAX_DEFAULT = 30
MAX_SUMMARY = 300
# a full stop before a capital, a quote or the end; never "e.g.", "et al."
# or the dots of "1, 2, ..."
_SENTENCE_END = re.compile(r"(?<!\be\.g)(?<!\bi\.e)(?<!\bcf)(?<!\bvs)(?<!\bal)(?<!\.)"
                           r"\.(?!\.)(?=\s+[A-Z`*(]|$)")


@dataclass(frozen=True)
class Entry:
    name: str             # dotted: smappy.beads.select_beads
    kind: str             # "function" or "class"
    signature: str
    summary: str          # the docstring's first sentence
    words: Tuple[FrozenSet[str], ...]   # per `_WEIGHTS`, in its order

    def as_dict(self) -> Dict[str, str]:
        return {"name": self.name, "kind": self.kind,
                "signature": self.signature, "doc": self.summary}


def first_sentence(doc: Optional[str]) -> str:
    """The first sentence of a docstring's first paragraph, on one line --
    not its first line, which in this code base is often half a sentence."""
    if not doc:
        return ""
    paragraph = re.split(r"\n\s*\n", doc.strip(), maxsplit=1)[0]
    text = " ".join(paragraph.split()).replace("``", "`")
    end = _SENTENCE_END.search(text)
    if end:
        text = text[:end.end()]
    return text if len(text) <= MAX_SUMMARY else text[:MAX_SUMMARY - 3] + "..."


def _default(node: ast.AST) -> str:
    text = ast.unparse(node)
    return text if len(text) <= MAX_DEFAULT else "..."


def signature(node: ast.AST) -> str:
    """``(a, b=1, *, c=None) -> Type``: the names and defaults without the
    parameters' annotations, which double a signature's length and are in
    the code; the return annotation kept, as it says what comes back."""
    if isinstance(node, ast.ClassDef):
        init = next((n for n in node.body if isinstance(n, ast.FunctionDef)
                     and n.name == "__init__"), None)
        if init is None:
            return ""
        node = init
    a = node.args
    parts: List[str] = []
    positional = a.posonlyargs + a.args
    defaults = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    for i, (arg, default) in enumerate(zip(positional, defaults)):
        parts.append(arg.arg if default is None else f"{arg.arg}={_default(default)}")
        if a.posonlyargs and i == len(a.posonlyargs) - 1:
            parts.append("/")
    if a.vararg:
        parts.append(f"*{a.vararg.arg}")
    elif a.kwonlyargs:
        parts.append("*")
    for arg, default in zip(a.kwonlyargs, a.kw_defaults):
        parts.append(arg.arg if default is None else f"{arg.arg}={_default(default)}")
    if a.kwarg:
        parts.append(f"**{a.kwarg.arg}")
    if parts and parts[0] in ("self", "cls") and node.name == "__init__":
        parts = parts[1:]
    text = f"({', '.join(parts)})"
    if node.returns is not None and node.name != "__init__":
        text += f" -> {ast.unparse(node.returns)}"
    return text if len(text) <= MAX_SIGNATURE else text[:MAX_SIGNATURE - 4] + "...)"


def _exported(tree: ast.Module) -> Optional[FrozenSet[str]]:
    """A module's ``__all__``, when it is a literal list of names."""
    for node in tree.body:
        if (isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets)):
            try:
                return frozenset(ast.literal_eval(node.value))
            except ValueError:
                return None
    return None


def _mentions(module_doc: str, names: Iterable[str]) -> Dict[str, str]:
    """Per name, the paragraphs of the module's docstring that name it in
    backticks (`select_beads`, `beads.select_beads`)."""
    names = set(names)
    out: Dict[str, List[str]] = {}
    for paragraph in re.split(r"\n\s*\n", module_doc):
        for quoted in re.findall(r"`+([A-Za-z_][\w.]*)", paragraph):
            name = quoted.rsplit(".", 1)[-1]
            if name in names and paragraph not in out.setdefault(name, []):
                out[name].append(paragraph)
    return {name: " ".join(found) for name, found in out.items()}


def _name_words(name: str) -> FrozenSet[str]:
    return frozenset(words(name.replace("_", " ")))


def module_entries(path: Path, dotted: str, functions_only: bool = False) -> List[Entry]:
    """The public functions and classes at one module's top level."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), str(path))
    except (SyntaxError, UnicodeDecodeError, OSError):
        return []
    exported = _exported(tree)
    kinds = (ast.FunctionDef, ast.AsyncFunctionDef) + (() if functions_only else (ast.ClassDef,))
    nodes = [n for n in tree.body if isinstance(n, kinds) and not n.name.startswith("_")
             and (exported is None or n.name in exported)]
    module_doc = ast.get_docstring(tree) or ""
    mentions = _mentions(module_doc, (n.name for n in nodes))
    module_words = frozenset(words(" ".join(dotted.split(".")[1:]).replace("_", " "))
                             + words(first_sentence(module_doc)))
    out = []
    for node in nodes:
        doc = ast.get_docstring(node) or ""
        summary = first_sentence(doc)
        out.append(Entry(
            f"{dotted}.{node.name}",
            "class" if isinstance(node, ast.ClassDef) else "function",
            signature(node), summary,
            (_name_words(node.name), module_words, frozenset(words(summary)),
             frozenset(words(doc)), frozenset(words(mentions.get(node.name, ""))))))
    return out


def package_folder() -> Path:
    from .. import __file__ as package
    return Path(package).resolve().parent


@lru_cache(maxsize=1)
def entries() -> Tuple[Entry, ...]:
    """Every public function and class of smappy's modules, once per process.

    Parsing the four hundred files costs about a second, and nothing is
    imported.  The plugins' modules give their functions only: their classes
    are the plugins and their settings, which `find_plugins` finds."""
    root = package_folder()
    out: List[Entry] = []
    for path in sorted(root.rglob("*.py")):
        relative = path.relative_to(root)
        if relative.parts[0] in _SKIPPED or any(
                p.startswith("_") and p != "__init__.py" for p in relative.parts):
            continue
        parts = ["smappy", *relative.with_suffix("").parts]
        if parts[-1] == "__init__":
            parts = parts[:-1]
        out += module_entries(path, ".".join(parts),
                              functions_only=relative.parts[0] == "plugins")
    return tuple(out)


def search(query: str, limit: int = 8) -> List[Dict[str, str]]:
    """The functions and classes that share most words with ``query``, best
    first; words the query negates count for none, as in `index.search`."""
    wanted = set(wanted_words(query))
    if not wanted:
        return []
    scored = []
    for entry in entries():
        score = sum(weight * len(wanted & found)
                    for (_, weight), found in zip(_WEIGHTS, entry.words))
        if score:
            # a function before a class of the same score: it is what is called
            scored.append((-score, entry.kind != "function", entry.name, entry))
    scored.sort(key=lambda s: s[:3])
    return [entry.as_dict() for *_, entry in scored[:limit]]
